import { localAuth } from './fixtures/gitee'
import { expect, test } from './support/test'

test.use({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, scenario: { following: false } })

test('mobile comment surfaces cover safe areas and reserve their measured height', async ({ page, context }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const session = await context.newCDPSession(page)
  await session.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 58, bottom: 34, left: 0, right: 0 } })
  await page.addInitScript(auth => localStorage.setItem('USER-AUTH', auth), localAuth())
  await page.goto('feedback/topic/123')
  await session.send('Emulation.setSmallViewportHeightDifferenceOverride', { difference: 80 })
  const dock = page.locator('.comment-input-mobile')
  await expect(dock).toBeVisible({ timeout: 30_000 })
  await expect(dock).toHaveCSS('padding-bottom', '42px')
  const entry = page.locator('.mobile-comment-entry')
  await expect(entry).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  const entryBackground = await entry.evaluate(el => getComputedStyle(el).backgroundColor)
  await entry.locator('.mobile-comment-entry-text').hover()
  await expect(entry).not.toHaveCSS('background-color', entryBackground)
  await expect(entry.locator('.mobile-comment-entry-text')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(entry.locator('.mobile-comment-entry-tools')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  expect(await entry.locator('.mobile-comment-entry-tools button').evaluateAll(buttons => buttons.every(button => getComputedStyle(button).backgroundColor === 'rgba(0, 0, 0, 0)'))).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('comment-entry-unified-background.png'), animations: 'disabled' })
  await page.mouse.move(0, 0)
  await expect.poll(() => dock.evaluate(el => getComputedStyle(el, '::after').height)).toBe('114px')
  await expect.poll(() => page.locator('.forum-comment-surface').evaluate((el) => {
    const dock = document.querySelector('.comment-input-mobile')!
    return Number.parseFloat(getComputedStyle(el).paddingBottom) - dock.getBoundingClientRect().height
  })).toBe(16)
  expect(await dock.evaluate(el => getComputedStyle(el, '::after').backgroundColor)).toBe(await dock.evaluate(el => getComputedStyle(el).backgroundColor))
  await page.screenshot({ path: testInfo.outputPath('comment-safe-area-light.png'), animations: 'disabled' })

  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await expect(dock).toHaveCSS('background-color', 'rgb(27, 27, 31)')
  await entry.locator('.mobile-comment-entry-text').hover()
  await expect(entry.locator('.mobile-comment-entry-text')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(entry.locator('.mobile-comment-entry-tools')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await page.mouse.move(0, 0)
  expect(await dock.evaluate(el => getComputedStyle(el, '::after').backgroundColor)).toBe('rgb(27, 27, 31)')
  await page.screenshot({ path: testInfo.outputPath('comment-safe-area-dark.png'), animations: 'disabled' })

  await page.locator('.mobile-comment-entry-text').click()
  const panel = page.getByRole('dialog', { name: '评论', exact: true })
  await expect(panel.locator('[contenteditable="true"]')).toBeFocused()
  await expect(dock).toBeHidden()
  await expect(panel).toHaveCSS('padding-bottom', '34px')
  await expect(panel).toHaveCSS('background-color', 'rgb(27, 27, 31)')
  await expect.poll(() => panel.evaluate(el => getComputedStyle(el, '::after').height)).toBe('114px')
  await panel.getByRole('button', { name: '展开编辑窗口', exact: true }).click()
  await expect.poll(() => panel.evaluate(el => Math.round(el.getBoundingClientRect().top))).toBe(58)
  await page.screenshot({ path: testInfo.outputPath('comment-editor-expanded.png'), animations: 'disabled' })
  await panel.locator('[contenteditable="true"]').fill('安全区切换保留草稿')
  // Simulate the visual viewport shrinking while the editor owns focus.
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport, 'height', { configurable: true, value: window.innerHeight - 300 })
    window.visualViewport!.dispatchEvent(new Event('resize'))
  })
  await expect(panel).toHaveClass(/keyboard-visible/)
  await expect(panel).toHaveCSS('padding-bottom', '0px')
  await expect.poll(() => panel.evaluate(el => getComputedStyle(el, '::after').display)).toBe('none')
  await expect.poll(() => panel.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBe(512)
  await expect.poll(() => panel.evaluate(el => Math.round(el.getBoundingClientRect().top))).toBe(58)
  await page.screenshot({ path: testInfo.outputPath('comment-editor-keyboard.png'), animations: 'disabled' })
  await page.evaluate(() => {
    Reflect.deleteProperty(window.visualViewport!, 'height')
    window.visualViewport!.dispatchEvent(new Event('resize'))
  })
  await expect(panel).not.toHaveClass(/keyboard-visible/)
  await expect(panel).toHaveCSS('padding-bottom', '34px')
  await expect.poll(() => panel.evaluate(el => getComputedStyle(el, '::after').display)).not.toBe('none')
  await page.locator('[data-slot=dialog-overlay]').click({ position: { x: 4, y: 4 } })
  await expect(panel).toHaveCount(0)
  await expect(dock).toBeVisible()

  await page.setViewportSize({ width: 740, height: 375 })
  await session.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 0, bottom: 21, left: 44, right: 44 } })
  await expect(dock).toHaveCSS('padding-left', '44px')
  await expect(dock).toHaveCSS('padding-right', '44px')
  await expect(dock).toHaveCSS('padding-bottom', '29px')
  await expect.poll(() => page.locator('.forum-comment-surface').evaluate((el) => {
    const dock = document.querySelector('.comment-input-mobile')!
    return Number.parseFloat(getComputedStyle(el).paddingBottom) - dock.getBoundingClientRect().height
  })).toBe(16)
  await page.locator('.mobile-comment-entry-text').click()
  await expect(panel.locator('[contenteditable="true"]')).toContainText('安全区切换保留草稿')
  await expect(panel.locator('.mobile-comment-editor')).toHaveCSS('padding-left', '44px')
  await expect(panel.locator('.mobile-comment-editor')).toHaveCSS('padding-right', '44px')
  await panel.locator('.editor-tools-row').getByRole('button', { name: '表情', exact: true }).click()
  await expect(panel.locator('.emoji-list')).toBeVisible()
  await expect.poll(() => panel.locator('.rich-editor-scroll').evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(26)
  const publish = panel.getByRole('button', { name: '发布', exact: true })
  await expect.poll(() => publish.evaluate(el => Math.round(el.getBoundingClientRect().bottom))).toBeLessThanOrEqual(354)
  await page.screenshot({ path: testInfo.outputPath('comment-editor-landscape-emoji.png'), animations: 'disabled' })
  await panel.locator('.emoji-list button').first().click()
  await expect(panel.locator('[contenteditable="true"] [data-emoji]')).toHaveCount(1)
  expect(errors).toEqual([])
})
